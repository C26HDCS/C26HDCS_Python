@unittest.skipUnless(os.getenv('HDCS_TEST_POSTGRES') == '1', 'Requires an isolated PostgreSQL test database')
class PostgresPipelineTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        settings = db.postgres_settings()
        if settings['host'] not in ('127.0.0.1', 'localhost') or not settings['dbname'].startswith('hdcs_test_'):
            raise RuntimeError('Tests require a disposable localhost hdcs_test_* database')
        if os.getenv('HDCS_DB_BACKEND') != 'postgresql':
            raise RuntimeError('PostgreSQL backend must be explicitly enabled')
        cls.sql = Path(os.getenv('HDCS_SCHEMA_SQL',
            str(Path(__file__).resolve().parents[2] / 'C26HDCS_WebService/src/main/resources/sql/python_pipeline_postgresql.sql'))).read_text(encoding='utf-8')
        with db.open_postgres() as connection:
            connection.execute('''
                CREATE TABLE IF NOT EXISTS public.tb_device (device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
                CREATE SEQUENCE IF NOT EXISTS public.dcs_data_seq;
                CREATE SEQUENCE IF NOT EXISTS public.ka_data_seq;
                CREATE TABLE IF NOT EXISTS public.tb_dcs_data (
                    dcs_data_id BIGINT DEFAULT nextval('dcs_data_seq') PRIMARY KEY,
                    device_id BIGINT NOT NULL REFERENCES public.tb_device(device_id),
                    data_payload VARCHAR(500) NOT NULL, received_status VARCHAR(20) NOT NULL,
                    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                );
                CREATE TABLE IF NOT EXISTS public.tb_ka_data (
                    ka_data_id BIGINT DEFAULT nextval('ka_data_seq') PRIMARY KEY,
                    device_id BIGINT NOT NULL REFERENCES public.tb_device(device_id),
                    file_path VARCHAR(500) NOT NULL, received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    file_size BIGINT, file_name VARCHAR(255) NOT NULL, receive_status VARCHAR(20) NOT NULL
                );
            ''')
            connection.execute(cls.sql)
            connection.execute(cls.sql)
            from status_fixture import provision
            provision(connection)

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.sqlite_path = self.root / 'unused.sqlite3'
        self.camera = 'cam_' + uuid.uuid4().hex
        self.source = 'tcp:' + uuid.uuid4().hex
        self.incoming = self.root / 'incoming'
        self.incoming.mkdir()
        self.received = []
        with db.open_postgres() as connection:
            self.device = connection.execute('INSERT INTO public.tb_device DEFAULT VALUES RETURNING device_id').fetchone()[0]
            connection.execute('''INSERT INTO public.tb_python_device_mapping VALUES ('DCS', '44/56/01', %s, TRUE)
                ON CONFLICT (data_kind,external_key) DO UPDATE SET device_id=excluded.device_id''', (self.device,))
            connection.execute("INSERT INTO public.tb_python_device_mapping VALUES ('KA', %s, %s, TRUE)", (self.camera, self.device))

    def server(self, server):
        thread = threading.Thread(target=server.serve_forever)
        thread.start()
        def stop():
            server.shutdown()
            thread.join(5)
            server.server_close()
        self.addCleanup(stop)
        return server

    def receive_ka(self, camera=None):
        (self.incoming / 'clip.mp4').write_bytes(b'video-bytes' * 100000)
        (self.incoming / 'clip.dump').touch()
        with KaReceiver(self.incoming, self.root / 'archive', self.sqlite_path,
                        camera or self.camera, settle_seconds=0) as receiver:
            result = receiver.scan_once()[0]
        return result

    def test_dcs_save_monitor_send_and_original_table(self):
        with FrameStore(self.sqlite_path) as store:
            receipt = Ingestor(store, self.source).feed(bytes.fromhex(SAMPLE_HEX))[0]
        monitor = DcsMonitor(self.sqlite_path, source_prefix=self.source)
        self.assertEqual(monitor.check().snapshot.status, 'RECEIVING')
        self.assertFalse(monitor.check().changed)
        with db.open_postgres() as connection:
            row = connection.execute('''SELECT b.device_id, b.data_payload, b.received_status,
                d.document_xor_matches, d.dcs_data_id FROM public.tb_dcs_data b
                JOIN public.tb_dcs_receive_details d ON b.dcs_data_id = d.dcs_data_id WHERE d.id=%s''',
                (receipt.row_id,)).fetchone()
            self.assertEqual(row[:3], (self.device, bytes.fromhex(SAMPLE_HEX).hex().upper(), 'SUCCESS'))
            self.assertIs(row[3], False)
        server = self.server(dcs_sink(port=0, on_receive=self.received.append))
        destination = 'dcs_' + uuid.uuid4().hex
        for expected in [1, 0]:
            with DcsSender(self.sqlite_path, destination_id=destination,
                           source_prefix=self.source, url=f'http://127.0.0.1:{server.server_port}/dcs') as sender:
                self.assertEqual(sender.send_ready().sent, expected)
        self.assertEqual(len(self.received), 1)
        self.assertFalse(self.sqlite_path.exists())

    def test_ka_save_monitor_send_and_original_table(self):
        result = self.receive_ka()
        self.assertEqual(result.status, 'RECEIVED', result.detail)
        monitor = KaMonitor(self.sqlite_path, self.camera)
        self.assertEqual(monitor.check().snapshot.data_status, 'RECEIVING')
        self.assertFalse(monitor.check().changed)
        with db.open_postgres() as connection:
            row = connection.execute('''SELECT b.device_id,b.file_name,b.receive_status,b.file_size
                FROM public.tb_ka_data b JOIN public.tb_ka_receive_details d ON d.ka_data_id=b.ka_data_id
                WHERE d.camera_id=%s''', (self.camera,)).fetchone()
            self.assertEqual(row, (self.device, 'clip.mp4', 'SUCCESS', 1100000))
        target = self.root / 'target'
        server = self.server(ka_sink(target, port=0))
        destination = 'ka_' + uuid.uuid4().hex
        for expected in [1, 0]:
            with KaSender(self.sqlite_path, destination_id=destination, camera_id=self.camera,
                          url=f'http://127.0.0.1:{server.server_port}/ka') as sender:
                self.assertEqual(sender.send_ready().sent, expected)
        received = next(target.glob('*/clip.mp4'))
        self.assertEqual(received.read_bytes(), (self.incoming / 'clip.mp4').read_bytes())

    def test_unmapped_dcs_preserved_but_not_forwarded(self):
        payload = bytearray.fromhex(SAMPLE_HEX)
        payload[1:3] = b'99'
        with FrameStore(self.sqlite_path) as store:
            receipt = Ingestor(store, self.source).feed(bytes(payload))[0]
        self.assertIn('44/56/99', receipt.mapping_error)
        with db.open_postgres() as connection:
            row = connection.execute('SELECT dcs_data_id, raw_hex, mapping_error FROM public.tb_dcs_receive_details WHERE id=%s', (receipt.row_id,)).fetchone()
            self.assertIsNone(row[0])
            self.assertEqual(row[1], bytes(payload).hex().upper())
            self.assertIn('44/56/99', row[2])
        self.assertEqual(DcsMonitor(self.sqlite_path, source_prefix=self.source).check().snapshot.status, 'INVALID_ONLY')
        with DcsSender(self.sqlite_path, destination_id=uuid.uuid4().hex, source_prefix=self.source,
                       url='http://127.0.0.1:1/dcs') as sender:
            self.assertEqual(sender.send_ready().enqueued, 0)

    def test_unmapped_ka_rolls_back_and_recovers(self):
        unknown = 'unknown_' + uuid.uuid4().hex
        result = self.receive_ka(unknown)
        self.assertEqual(result.status, 'ERROR')
        self.assertEqual(list((self.root / 'archive' / unknown).glob('*.mp4')), [])
        self.assertTrue((self.incoming / 'clip.mp4').exists())
        with db.open_postgres() as connection:
            connection.execute("INSERT INTO public.tb_python_device_mapping VALUES ('KA', %s, %s, TRUE)", (unknown, self.device))
        with KaReceiver(self.incoming, self.root / 'archive', self.sqlite_path, unknown, settle_seconds=0) as receiver:
            self.assertEqual(receiver.scan_once()[0].status, 'RECEIVED')

    def test_ka_parent_rolls_back_when_details_conflict(self):
        self.assertEqual(self.receive_ka().status, 'RECEIVED')
        with closing(db.connect(self.sqlite_path)) as connection:
            connection.row_factory = db.Row
            original = dict(connection.execute('SELECT * FROM ka_video_receipts WHERE camera_id=?', (self.camera,)).fetchone())
            values = tuple(original[k] for k in ('received_at','camera_id','source_path','marker_path',
                          'marker_mtime_ns','marker_size','archive_path','byte_size','sha256'))
            try:
                with self.assertRaises(db.Error):
                    db.save_ka(connection, values)
            finally:
                connection.rollback()
        with db.open_postgres() as connection:
            self.assertEqual(connection.execute('SELECT count(*) FROM public.tb_ka_data WHERE device_id=%s', (self.device,)).fetchone()[0], 1)

    def test_postgres_retry_and_claim_ownership(self):
        self.receive_ka()
        server = self.server(ka_sink(self.root / 'target', port=0))
        options = dict(destination_id='retry_' + uuid.uuid4().hex, camera_id=self.camera,
                       url=f'http://127.0.0.1:{server.server_port}/ka')
        with KaSender(self.sqlite_path, **options) as first:
            first.enqueue_new()
            claim = first._claim()
            with KaSender(self.sqlite_path, **options) as other:
                self.assertEqual(other.send_ready().sent, 0)
            first._renew(claim)
            first._finish(claim, 503, 'Temporary error')
            self.assertEqual(first.send_ready().sent, 0)
        with db.open_postgres() as connection:
            connection.execute("UPDATE public.tb_ka_delivery_jobs SET next_attempt_at=now()-interval '1 minute' WHERE destination_id=%s", (options['destination_id'],))
        with KaSender(self.sqlite_path, **options) as restarted:
            self.assertEqual(restarted.send_ready().sent, 1)
            row = restarted.connection.execute('SELECT status,attempts FROM ka_delivery_jobs WHERE destination_id=?', (options['destination_id'],)).fetchone()
            self.assertEqual(tuple(row), ('SENT', 2))


if __name__ == '__main__':
    unittest.main()
